import {
    NextFunction,
    Response
} from "express";

export default function noCache(req: any, res: Response, next: NextFunction) {
    res.set("Cache-Control", "no-store, no-cache, must-revalidate, private");
    res.set("Pragma", "no-cache");
    res.set("Expires", "0");

    return next();
}

